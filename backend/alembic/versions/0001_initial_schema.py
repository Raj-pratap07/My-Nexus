def _role_exists(role: str) -> str:
    # These roles exist only on Supabase; skip them on plain PostgreSQL.
    return f"IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{role}') THEN "


def _secure_tables_postgresql() -> None:
    context = op.get_context()
    if context.dialect.name != "postgresql":
        return  # SQLite (offline tests) has no RLS or roles.
    secured = APP_TABLES + (context.version_table,)
    for table in secured:
        op.execute(f'ALTER TABLE "{table}" ENABLE ROW LEVEL SECURITY')
    tables = ", ".join(f'"{t}"' for t in secured)
    for role in SUPABASE_API_ROLES:
        op.execute(
            "DO $$ BEGIN " + _role_exists(role)
            + f'REVOKE ALL ON TABLE {tables} FROM "{role}"; '
            "END IF; END $$"
        )
    # Fail closed: REVOKE only removes grants made by this role (or the
    # owner), and privileges can also arrive via PUBLIC or role membership.
    # has_table_privilege() sees all of those; if any remains, abort so the
    # whole migration rolls back.
    table_array = ", ".join(f"'{t}'" for t in secured)
    for role in SUPABASE_API_ROLES:
        op.execute(
            "DO $$ DECLARE t text; BEGIN " + _role_exists(role)
            + f"FOREACH t IN ARRAY ARRAY[{table_array}] LOOP "
            f"IF has_table_privilege('{role}', quote_ident(t), '{TABLE_PRIVILEGES}') THEN "
            f"RAISE EXCEPTION USING MESSAGE = 'role {role} still holds a privilege on table ' || t; "
            "END IF; END LOOP; END IF; END $$"
        )


